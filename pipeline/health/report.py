"""docs/HEALTH.md and public/data/meta/health.json: one row per record (category, status, last data time, source latest,
lag, app plays, checks passed/failed, notes), then the freshness, S-NPP, archive and link tables. No secrets, no local
paths: notes are built from manifest fields and HTTP results only."""
import json, re
from collections import Counter
from svs.config import REPO
from .inventory import CATEGORIES, DATA

# A drive path (C:\… or C:/…, not the "s://" of a URL) or a home/tmp path, up to a space, quote or table bar.
LOCAL = re.compile(r"(?<![A-Za-z])[A-Za-z]:(?:\\|/(?!/))[^\s|\"']*|(?<![\w.:/])/(?:home|Users|tmp)/[^\s|\"']*")

def _scrub(s):
    return LOCAL.sub("<local path>", str(s)).replace("|", "/")

def _scrub_all(v):
    """Every string in a JSON value with local paths replaced (keys and structure unchanged)."""
    if isinstance(v, str): return LOCAL.sub("<local path>", v)
    if isinstance(v, dict): return {k: _scrub_all(x) for k, x in v.items()}
    if isinstance(v, list): return [_scrub_all(x) for x in v]
    return v

def _cell(v):
    return "—" if v in (None, "") else _scrub(v)

def row_summary(r):
    passed = sum(c["ok"] is True for c in r["checks"])
    failed = [c for c in r["checks"] if c["ok"] is False]
    return passed, failed

def markdown(doc):
    L = ["# Record health", "", f"Generated by `npm run health` (`python -m health` in `pipeline/`) on {doc['generated_utc']}. "
         "Checks only: nothing is refreshed by this command (`npm run refresh:live` refreshes).", "",
         "## Summary", "", "| Category | Records | All checks pass | With a failure |", "|---|---|---|---|"]
    by = Counter(r["category"] for r in doc["records"])
    for c in CATEGORIES:
        rs = [r for r in doc["records"] if r["category"] == c]
        bad = sum(1 for r in rs if row_summary(r)[1])
        L.append(f"| {CATEGORIES[c]} | {by[c]} | {len(rs) - bad} | {bad} |")
    app = doc.get("app") or {}
    L += ["", f"App checks: {app.get('summary', 'not run (python -m health --app runs e2e/health-records.e2e.ts)')}", "",
          "## Records", "", "| Record | Category | Status | Last data (UTC) | Source latest (UTC) | Lag (d) | App plays | Checks | Notes |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in doc["records"]:
        passed, failed = row_summary(r)
        notes = "; ".join(f"{c['check']}: {c['note']}" for c in failed)[:300] or "; ".join(r.get("notes", []))
        L.append(f"| {r['id']} | {CATEGORIES[r['category']]} | {_cell(r['status'])} | {_cell(r.get('last_data_utc'))} | "
                 f"{_cell(r.get('source_latest_utc'))} | {_cell(r.get('lag_days'))} | {_cell(r.get('app_plays'))} | "
                 f"{passed} passed, {len(failed)} failed | {_cell(notes)} |")
    hid = doc.get("hidden") or []
    L += ["", "## Hidden from the Related shelf", "", "Kept off the shelf by a feature flag (pipeline/svs/onboard HIDDEN; the app lists them "
          "only with NEXT_PUBLIC_SHOW_HIDDEN_RELATED=1), so the app check does not play them. Their files stay in public/data/related/.", ""]
    L += ["| Record | Title | Why |", "|---|---|---|"] + [f"| {h['record']} | {_cell(h['title'])} | {_cell(h['reason'])} |" for h in hid] if hid else ["None."]
    L += ["", "## Freshness (records that can update)", "",
          "| Record | Shipped (UTC) | Source latest (UTC) | Age (d) | Lag (d) | Limit (d) | Behind limit | Source asked |", "|---|---|---|---|---|---|---|---|"]
    for f in doc["freshness"]:
        L.append(f"| {f['record']} | {_cell(f['shipped_utc'])} | {_cell(f['source_latest_utc'])} | {_cell(f['age_days'])} | {_cell(f['lag_days'])} | "
                 f"{_cell(f['limit_days'])} | {'**yes**' if f['behind_limit'] else 'no'} | {_cell(f['source'])} |")
    s = doc.get("snpp") or {}
    L += ["", "## S-NPP (retired 2 Nov 2026)", "", f"Current records reading S-NPP: {s.get('current_records_reading_snpp') or 'none'}.", "",
          "| S-NPP product | Latest | Stopped | NOAA-20/21 equivalent | Its latest |", "|---|---|---|---|---|"]
    for p in s.get("products", []):
        L.append(f"| {p['product']} | {_cell(p['snpp_latest_utc'])} | {'yes' if p['stopped'] else 'no'} | {p['replacement']} | {_cell(p['replacement_latest_utc'])} |")
    arch = doc.get("archive") or []
    ch = [a for a in arch if a.get("changed")]
    L += ["", "## Archive items vs pipeline/svs/cache", "", f"{len(arch)} archive SVS items checked; {len(ch)} changed since ingest.", ""]
    if ch:
        L += ["| SVS | Record | What changed |", "|---|---|---|"]
        for a in ch:
            what = a.get("error") or "; ".join(x for x in (
                f"update date {a['update_date'][0]} → {a['update_date'][1]}" if a.get("update_date") and a["update_date"][0] != a["update_date"][1] else "",
                "title" if a.get("title_changed") else "", f"{len(a['assets_added'])} assets added" if a.get("assets_added") else "",
                f"{len(a['assets_removed'])} assets removed" if a.get("assets_removed") else "", "; ".join(a.get("size_changes", []))) if x)
            L.append(f"| {a['svs_id']} | {a['record']} | {_cell(what)} |")
    un = [a for a in arch if a.get("size_unchecked")]
    if un:
        L += ["", f"Asset sizes not checked for {len(un)} items (the server refused or timed out, so not counted as a change): "
              + "; ".join(f"{a['svs_id']} ({a['size_unchecked'][0]})" for a in un[:6]) + (" …" if len(un) > 6 else "")]
    bad ={u: s for u, s in (doc.get("links") or {}).items() if not (isinstance(s, int) and 200 <= s < 400)}
    dead = {u: s for u, s in bad.items() if s != 403}
    no = sorted(u for u, s in bad.items() if s == 403)
    svs = [u for u in no if "svs.gsfc.nasa.gov/vis/" in u]
    L += ["", "## Links that do not resolve", "", f"{len(doc.get('links') or {})} unique links checked; {len(dead)} do not resolve "
          f"(timeouts, connection errors, 4xx/5xx other than 403); {len(no)} refused automated requests (403: unverified, "
          "may open in a browser).", ""]
    L += [f"- `{s}` {u}" for u, s in sorted(dead.items())] or ["None."]
    if no:
        L += ["", f"Refused (403), unverified: {len(svs)} SVS file links (svs.gsfc.nasa.gov/vis/…; SVS refused every file "
              "request from this machine at the time of the run, while its API and pages answered)" if svs else "Refused (403), unverified:", ""]
        L += [f"- {u}" for u in no if u not in svs]
    return "\n".join(L) + "\n"

def write(doc):
    (REPO / "docs" / "HEALTH.md").write_text(markdown(doc), encoding="utf-8")
    body = json.dumps(_scrub_all(doc), indent=1, ensure_ascii=False)
    (DATA / "meta" / "health.json").write_text(body, encoding="utf-8")
