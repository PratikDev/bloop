"""Shared validation statistics and their record: validation.json per record (next to its manifest) and one row per
check in docs/official/VALIDATION_TABLE.md. Thresholds are provisional and passed in by the caller; a miss is reported
with the real number, never relaxed here."""
import json, re
import numpy as np
from scipy import stats
from common import now_utc
from .config import DOCS_OFFICIAL, PUBLIC_OFFICIAL

def _pairs(a, b):
    a, b = np.asarray(a, float).ravel(), np.asarray(b, float).ravel()
    ok = np.isfinite(a) & np.isfinite(b)
    return a[ok], b[ok]

def spearman(a, b):
    a, b = _pairs(a, b)
    return (float(stats.spearmanr(a, b).statistic), len(a)) if len(a) >= 8 else (float("nan"), len(a))

def errors(pred, truth):
    """Median |error|, median relative |error| (vs truth), bias (mean pred − truth), n."""
    p, t = _pairs(pred, truth)
    if not len(p): return {"n": 0}
    rel = np.abs(p - t) / np.maximum(np.abs(t), 1e-12)
    return {"n": int(len(p)), "median_abs": float(np.median(np.abs(p - t))), "median_rel": float(np.median(rel)),
            "bias": float(np.mean(p - t)), "median_bias": float(np.median(p - t))}

def sign_agreement(a, b, min_abs=0.0):
    a, b = _pairs(a, b)
    keep = (np.abs(a) > min_abs) & (np.abs(b) > min_abs)
    return (float(np.mean(np.sign(a[keep]) == np.sign(b[keep]))), int(keep.sum())) if keep.any() else (float("nan"), 0)

def angle_diff(a_deg, b_deg, axial=False):
    """Absolute angular difference in degrees: 0–180 for directions, 0–90 for axes (mod 180)."""
    period = 180.0 if axial else 360.0
    d = (np.asarray(a_deg, float) - np.asarray(b_deg, float)) % period
    return np.minimum(d, period - d)

def distribution(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    a, b = a[np.isfinite(a)], b[np.isfinite(b)]
    return {"ks": float(stats.ks_2samp(a, b).statistic), "wasserstein": float(stats.wasserstein_distance(a, b)),
            "median_a": float(np.median(a)), "median_b": float(np.median(b)), "n_a": int(len(a)), "n_b": int(len(b))}

def check(record, cid, title, metrics, threshold=None, passed=None, kind="value", source=None, note=""):
    """One validation result. kind: value (frame vs same model) | model-vs-obs | context | none."""
    return {"record": record, "id": cid, "title": title, "kind": kind, "source": source, "metrics": metrics,
            "threshold": threshold, "pass": passed, "note": note, "run_utc": now_utc()}

def _clean(o):
    if isinstance(o, dict): return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)): return [_clean(v) for v in o]
    if isinstance(o, (np.floating, float)): return None if not np.isfinite(o) else float(o)
    if isinstance(o, np.integer): return int(o)
    if isinstance(o, np.bool_): return bool(o)
    return o

def save(record, checks):
    """validation.json (merged by check id) + the record's rows in VALIDATION_TABLE.md."""
    path = PUBLIC_OFFICIAL / record / "validation.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    old = {c["id"]: c for c in json.loads(path.read_text(encoding="utf-8"))["checks"]} if path.exists() else {}
    old.update({c["id"]: _clean(c) for c in checks})
    doc = {"record": record, "checks": list(old.values()), "updated_utc": now_utc()}
    path.write_text(json.dumps(doc, indent=1, ensure_ascii=False, allow_nan=False), encoding="utf-8")
    _table(record, doc["checks"])
    return doc

def _fmt(m):
    keys = [k for k in m if not isinstance(m[k], (dict, list))][:6]
    return "; ".join(f"{k} {m[k]:.3g}" if isinstance(m[k], float) else f"{k} {m[k]}" for k in keys)

def _table(record, checks):
    path = DOCS_OFFICIAL / "VALIDATION_TABLE.md"
    head = ["# Validation table (generated by pipeline/svs/validate.py)", "",
            "Thresholds are provisional. A miss shows the real number; it is never relaxed silently.", "",
            "| Record | Check | Kind | Source | Key numbers | Threshold | Result |", "|---|---|---|---|---|---|---|"]
    rows = path.read_text(encoding="utf-8").splitlines()[len(head):] if path.exists() else []
    rows = [r for r in rows if not r.startswith(f"| {record} |")]
    for c in checks:
        res = "no threshold" if c["pass"] is None else ("PASS" if c["pass"] else "MISS")
        rows.append(f"| {record} | {c['id']}: {c['title']} | {c['kind']} | {c['source'] or ''} | {_fmt(c['metrics'])} | "
                    f"{c['threshold'] or ''} | {res} |")
    DOCS_OFFICIAL.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(head + sorted(rows, key=lambda r: re.sub(r'\s+', ' ', r))) + "\n", encoding="utf-8")
