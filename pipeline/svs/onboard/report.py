"""The related records at a glance, from their own files: ID, title, EIC focus area, the official item beside it, status,
key numbers of its check, size; plus the folder total against the 150 MB budget. Writes docs/related/RELATED_RECORDS.md.
Usage (from pipeline/): python -m svs.onboard.report"""
import json
from ..config import PUBLIC_RELATED, RELATED_BUDGET_BYTES, REPO

def key(c):
    m = c["metrics"]
    if "spearman" in m and m["spearman"] is not None:
        bits = [f"ρ {m['spearman']:.2f}"]
        if m.get("median_rel_error") is not None: bits.append(f"error {m['median_rel_error']:.0%}")
        if m.get("median_diff_C") is not None: bits.append(f"Δ {m['median_diff_C']:+.2f} °C")
        if m.get("rung"): bits.append(m["rung"])
        return ", ".join(bits)
    if "points" in m: return f"{m['points']} points, {m['first'][:4]}–{m['last'][:4]}"
    if "matched_share_of_opaque" in m: return f"{m['matched_share_of_opaque']:.2%} exact"
    return str(m.get("reason", ""))[:90]

def main():
    rows, total = [], 0
    for p in sorted(PUBLIC_RELATED.glob("rel_*/manifest.json")):
        m = json.loads(p.read_text(encoding="utf-8"))
        v = json.loads((p.parent / "validation.json").read_text(encoding="utf-8"))["checks"]
        size = sum(f.stat().st_size for f in p.parent.iterdir() if f.is_file()); total += size
        status = sorted({l["status"] for l in m["layers"]})
        rows.append(f"| {', '.join(map(str, m['svs_ids'])) or '—'} | {m['app_title'][:70]} | {m['focus']} | {', '.join(map(str, m['related_to'])) or '—'} | "
                    f"{'; '.join(status)} | {key(v[0]) if v else ''} | {size / 1e6:.2f} MB |")
    L = ["# Related records (public/data/related/)", "", "Generated by `pipeline/svs/onboard/report.py` from each record's manifest and "
         "validation file.", "", f"**{len(rows)} records, {total / 1e6:.1f} MB of {RELATED_BUDGET_BYTES / 1e6:.0f} MB.**", "",
         "| SVS ID | Record | Focus area | Beside official | Status | Key numbers | Size |", "|---|---|---|---|---|---|---|", *rows]
    (REPO / "docs" / "related" / "RELATED_RECORDS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(rows)} related records, {total / 1e6:.1f} MB")

if __name__ == "__main__":
    main()
