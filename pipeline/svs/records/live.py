"""EIC class-A items that a Bloop product already decodes every day (the live layer: 5101 SST, 4285 IMERG rain, 5176 SST
anomaly, 5315 Fire Weather Index, 5584 landslides, 5113 VIIRS fires): docs/official/<id>.md pointing to the product, and
validation rows copied from the 'verified' block the product writes into its own output file (code output, refreshed each
run). Nothing is re-decoded here; the inventory row and the product must agree (checked).
Usage (from pipeline/): python -m svs.records.live"""
import json
from products.registry import PRODUCTS
from svs import eic, validate as V
from svs.config import DOCS_OFFICIAL, REPO

def verified_of(product):
    path = REPO / "public" / "data" / product.outputs[0]
    if not path.exists() or path.suffix != ".json": return None, path
    d = json.loads(path.read_text(encoding="utf-8"))
    return d.get("verified"), path

def main():
    inv = {r["id"]: r for r in json.loads((eic.CACHE / "eic_inventory.json").read_text(encoding="utf-8"))["items"]}
    for sid, pid in sorted(eic.decoded_by().items()):
        if sid not in inv or inv[sid]["class"] != "A" or pid.startswith(("air_", "currents_", "lights_", "eic_")): continue
        p = PRODUCTS[pid]
        ver, path = verified_of(p)
        record = f"live_{pid}"
        if ver:
            metrics = {k: v for k, v in ver.items() if not isinstance(v, (dict, list))}
            check = V.check(record, f"a_{ver.get('test', 'acceptance')}", f"SVS {sid} live frame: acceptance test {ver.get('test', '')}",
                            kind="value", source=ver.get("against") or ver.get("matched_run"), metrics=metrics,
                            passed=None if ver.get("status") is None else ver["status"] == "PASS",
                            threshold=ver.get("status") and f"status {ver['status']} (the product's own thresholds)")
        else:
            check = V.check(record, "a_acceptance", f"SVS {sid} live frame: acceptance test in the reference suite", kind="none", passed=None,
                            metrics={"output": p.outputs[0]}, note="The product's output carries no verified block; see docs/data-integration-status.md.")
        V.save(record, [check])
        L = [f"# SVS {sid}: {inv[sid]['title']}", "", "Generated by `pipeline/svs/records/live.py`; do not edit by hand.", "",
             f"**Already decoded every day by Bloop product `{pid}`** ({p.title}; cadence {p.cadence}; outputs {', '.join(p.outputs)}). "
             "This EIC class-A item is the app's live layer, not an official-records entry.", "",
             f"- Credit: {p.credit or 'the output file’s own credit field'}", f"- Disclosure: {p.disclosure}", "",
             "## Validation (from the product's output file)", "",
             *([f"- {k}: {v}" for k, v in check["metrics"].items()] or ["- none recorded"]), "",
             f"Source file: `{path.relative_to(REPO).as_posix()}`."]
        (DOCS_OFFICIAL / f"{sid}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
        print(f"live {sid}: {pid} ({'verified' if ver else 'no verified block'})")

if __name__ == "__main__":
    main()
