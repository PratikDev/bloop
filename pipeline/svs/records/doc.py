"""docs/official/<svs id>.md for a record, rendered from its manifest.json and validation.json: what it is (the SVS
text), what we extracted, how, the validation numbers and the known limits. A record supplies only its method and limit
sentences as templates; every number in them is a {slot} filled from the record's own files.
Usage (from pipeline/): python -m svs.records.doc <record>"""
import importlib, json, sys
from svs.config import DOCS_OFFICIAL, PUBLIC_OFFICIAL

def fmt(v):
    if isinstance(v, bool) or v is None: return str(v)
    if isinstance(v, float): return f"{v:.3g}" if abs(v) < 1e4 else f"{v:,.0f}"
    if isinstance(v, int): return f"{v:,}"
    return str(v)

def metric_lines(metrics, prefix=""):
    out = []
    for k, v in metrics.items():
        if isinstance(v, dict):
            out += metric_lines(v, f"{prefix}{k} › ")
        elif isinstance(v, list):
            if v and isinstance(v[0], list) and len(v) > 12: out.append(f"- {prefix}{k}: {len(v)} rows (validation.json)")
            else: out.append(f"- {prefix}{k}: {', '.join(fmt(x) if not isinstance(x, list) else '/'.join(map(fmt, x)) for x in v)}")
        else:
            out.append(f"- {prefix}{k}: {fmt(v)}")
    return out

def render(record):
    m = json.loads((PUBLIC_OFFICIAL / record / "manifest.json").read_text(encoding="utf-8"))
    vfile = PUBLIC_OFFICIAL / record / "validation.json"
    checks = json.loads(vfile.read_text(encoding="utf-8"))["checks"] if vfile.exists() else []
    text = importlib.import_module(f"svs.records.{record.split('_')[0]}.doc_text")
    slots = text.slots(m, {c["id"]: c for c in checks})
    L = [f"# SVS {' / '.join(map(str, m['svs_ids']))}: {m['title']}", "",
         f"Generated by `pipeline/svs/records/doc.py` from `public/data/official/{record}/` ({m['generated_utc']}); do not edit by hand.", "",
         f"**App record:** {m['app_title']} · **Badge:** {m['badge']} · **Period:** {m['period']['label']} · "
         f"**Frame times:** {m['frame_times']['method']}{' (approximate)' if m['frame_times']['approximate'] else ''}", "",
         "## What it is (SVS text)", "", m["description"], "", "## What we extracted", "",
         "| Layer | Unit | Grid | Steps | Coverage | Encoding / step |", "|---|---|---|---|---|---|"]
    for l in m["layers"]:
        L.append(f"| {l['label']} (`{l['id']}`) | {l['unit']} | {l['grid']['width']}×{l['grid']['height']} over {l['grid']['bounds']} | "
                 f"{len(l['times'])} | {l['coverage']:.1%} | {l['encoding']} / {fmt(l['quantisation_step'])} |")
    L += ["", f"Size: {m['size']['bytes']:,} bytes (budget {m['size']['budget']:,}); choice {m['size']['choice']}.", "",
          "## How", ""] + [f"- {s.format(**slots)}" for s in text.METHOD] + ["", "## Validation", ""]
    for c in checks:
        res = "no threshold" if c["pass"] is None else ("PASS" if c["pass"] else "MISS (provisional threshold)")
        L += [f"### {c['id']}: {c['title']}", "", f"Kind: {c['kind']} · Source: {c['source']} · Threshold: {c['threshold'] or 'none'} · **{res}**", ""]
        if c.get("decision"):
            d = c["decision"]
            L += [f"**Team decision ({d['on']}):** shipped as *{d['status']}*: {d['statement']}. {d['table'][0].upper() + d['table'][1:]}.", ""]
        L += metric_lines(c["metrics"]) + ([f"", f"_{c['note']}_"] if c.get("note") else []) + [""]
    L += ["## Known limits", ""] + [f"- {s.format(**slots)}" for s in text.LIMITS]
    L += ["", "## Credits and licence", ""] + [f"- {role}: {'; '.join(p)}" for role, p in m["credits_by_role"].items()]
    L += [f"- {m['credit_line']}"] + [f"- {s['label']} ({s['badge']}, {s['period']}): {s['citation']['text']}" for s in m.get("voice_sources", {}).values()]
    L += [f"- {m['licence']}", "", f"Code commit: `{m['code_commit']}`. Asset checksums: `{m['asset_checksums']['file']}` "
          f"({m['asset_checksums']['rows']:,} rows, SHA-256 of the list {m['asset_checksums']['sha256_of_list'][:16]}…)."]
    path = DOCS_OFFICIAL / f"{m['svs_ids'][0]}.md"
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return path

if __name__ == "__main__":
    print(render(sys.argv[1]))
