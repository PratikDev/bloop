"""Regression gate for invert.py: on the existing SST truth test (Check C: the 5101 frame + 60 MUR points; book 0.31 °C
median, p90 0.77, bias +0.08) the CIELAB curve must not be worse than the old nearest-RGB lookup. Same strip, same
−4…34 °C calibration (lut_params.json); only the colour matching differs. The book's MUR column is the one whose old-
method numbers reproduce the book's (median, p90, bias); every column is reported. Also checks that
Inverter(method="rgb-nearest") reproduces convert_sst exactly. Writes docs/official/INVERSION_REGRESSION.md (+ .json).
Usage (from pipeline/): python -m svs.regression_sst"""
import json
import numpy as np
import pandas as pd
from common import INPUTS, load_params, now_utc
from convert_sst import invert_sst, read_frame, sst_lut
from core.log import say
from .colorbar import Colorbar
from .config import DOCS_OFFICIAL
from .invert import Inverter

MAX_DE = 10.0            # ΔE76 for lab-curve; fixed before the run (antialiased coastlines exceed it)

def errors(pred, truth):
    e = pred - truth
    ok = np.isfinite(e)
    return {"n": int(ok.sum()), "median_abs_C": float(np.median(np.abs(e[ok]))), "p90_abs_C": float(np.percentile(np.abs(e[ok]), 90)),
            "bias_C": float(np.mean(e[ok]))}

def main():
    P = load_params(); c = P["sst"]; book = c["verified"]
    frame = next(iter(sorted((INPUTS / "reference").glob("checkC_frame.*"))))
    pts = pd.read_csv(INPUTS / "reference" / "checkC_points_with_mur.csv")
    _, old_img, _ = invert_sst(frame, P)
    lut_rgb, _ = sst_lut(P)
    cb = Colorbar(rgb=lut_rgb, alpha=np.ones(len(lut_rgb)), geometry={"source": c["colorbar_file"]}, scale="linear",
                  fit={"a": c["vmin"], "b": (c["vmax"] - c["vmin"]) / (len(lut_rgb) - 1)})
    rgb, _ = read_frame(frame, c["exr_encoding"])
    same_img, _, _, _ = Inverter(cb, method="rgb-nearest").invert(rgb, c["max_colour_distance"])
    reproduces = bool(np.array_equal(np.isnan(same_img), np.isnan(old_img)) and np.nanmax(np.abs(same_img - old_img)) < 1e-4)
    new_img, _, _, _ = Inverter(cb, method="lab-curve").invert(rgb, MAX_DE)
    yx = (pts.y.values, pts.x.values)
    old, new = old_img[yx], new_img[yx]
    cols = {k: {"old": errors(old, pts[k].values), "new": errors(new, pts[k].values)} for k in pts.columns if k.startswith("mur_")}
    dist = lambda r: abs(r["median_abs_C"] - book["value"]) + abs(r["p90_abs_C"] - book["p90_abs_error_C"]) + abs(r["bias_C"] - book["bias_C"])
    col = min(cols, key=lambda k: dist(cols[k]["old"]))
    r_old, r_new = cols[col]["old"], cols[col]["new"]
    both = np.isfinite(old_img) & np.isfinite(new_img)
    d = np.abs(old_img[both] - new_img[both])
    not_worse = r_new["median_abs_C"] <= r_old["median_abs_C"]
    out = {"frame": frame.name, "book_column": col, "columns": cols, "rgb_nearest_reproduces_convert_sst": reproduces,
           "coverage_old": float(np.isfinite(old_img).mean()), "coverage_new": float(np.isfinite(new_img).mean()),
           "max_de": MAX_DE, "max_rgb_dist_old": c["max_colour_distance"],
           "frame_wide_abs_diff_C": {"median": float(np.median(d)), "p99": float(np.percentile(d, 99)), "max": float(d.max())},
           "verdict": "lab-curve not worse: it may be the default" if not_worse else "lab-curve WORSE on the median: rgb-nearest (old lookup) stays the default",
           "run_utc": now_utc()}
    row = lambda name, r, cov: f"| {name} | {r['n']} | {r['median_abs_C']:.3f} | {r['p90_abs_C']:.3f} | {r['bias_C']:+.3f} | {cov:.1%} |"
    lines = ["# Inversion regression: CIELAB curve vs the old nearest-RGB lookup", "",
             f"Generated by `pipeline/svs/regression_sst.py` ({out['run_utc']}). Check C = the 5101 SST frame with 60 ocean points and NASA MUR "
             f"values (`pipeline/inputs/reference/checkC_points_with_mur.csv`). The book's number (median {book['value']} °C, p90 "
             f"{book['p90_abs_error_C']}, bias {book['bias_C']:+}) is reproduced by the old method on column `{col}`.", "",
             f"## On the book's column `{col}`", "",
             "| Method | n | median \\|error\\| °C | p90 \\|error\\| °C | bias °C | frame pixels decoded |", "|---|---|---|---|---|---|",
             row(f"old: nearest RGB (≤ {c['max_colour_distance']} RGB units)", r_old, out["coverage_old"]),
             row(f"new: CIELAB curve projection (≤ ΔE {MAX_DE:g})", r_new, out["coverage_new"]), "",
             "## Every MUR column (same 60 points)", "", "| MUR column | old median / p90 / bias | new median / p90 / bias |", "|---|---|---|"]
    for k, v in cols.items():
        o, n = v["old"], v["new"]
        lines.append(f"| `{k}` | {o['median_abs_C']:.3f} / {o['p90_abs_C']:.3f} / {o['bias_C']:+.3f} | {n['median_abs_C']:.3f} / {n['p90_abs_C']:.3f} / {n['bias_C']:+.3f} |")
    lines += ["", f"Frame-wide |old − new| where both decode: median {out['frame_wide_abs_diff_C']['median']:.4f} °C, 99th percentile "
              f"{out['frame_wide_abs_diff_C']['p99']:.4f} °C, max {out['frame_wide_abs_diff_C']['max']:.3f} °C.",
              f"`Inverter(method=\"rgb-nearest\")` reproduces `convert_sst.invert_sst` exactly: {reproduces}.", "",
              f"**Verdict:** {out['verdict']}.", "",
             "Note: the 0.31 °C figure is SVS 5101's (SST frame vs MUR). SVS 5176's −0.31 °C is a different number: its offset vs "
             "NOAA Coral Reef Watch."]
    DOCS_OFFICIAL.mkdir(parents=True, exist_ok=True)
    (DOCS_OFFICIAL / "INVERSION_REGRESSION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (DOCS_OFFICIAL / "inversion_regression.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    say(f"book column {col}: old {r_old['median_abs_C']:.3f} °C, new {r_new['median_abs_C']:.3f} °C; reproduces {reproduces}; {out['verdict']}")
    return out

if __name__ == "__main__":
    main()
