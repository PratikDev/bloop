// The raw-pixel demo's stored measurement (public/data/art/raw_pixel.json): renders the naive and Bloop versions of
// SVS 3912's first frame (src/lib/art/raw-pixel) and measures flatness, entropy and roughness (metrics.ts). The app
// plays the same renders and shows these numbers; raw-pixel.test.ts checks they still match. Run: bun scripts/art-raw-pixel.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { frameFrom, RAW_LAYER, RAW_RECORD } from "../src/lib/art/raw-pixel/frame";
import { measure, stored } from "../src/lib/art/raw-pixel/metrics";
import { RAW_RATE, RAW_SECONDS, renderBloop, renderNaive } from "../src/lib/art/raw-pixel/render";
import type { OfficialManifest } from "../src/types/data-contract";

const dir = join(process.cwd(), "public", "data", "official", RAW_RECORD);
const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) as OfficialManifest;
const layer = manifest.layers.find((l) => l.id === RAW_LAYER);
if (!layer) throw new Error("no sst layer");
const raw = gunzipSync(readFileSync(join(dir, layer.chunks[0].file)));
const codes = new Uint16Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
const frame = frameFrom(layer, codes);
const out = {
  note: "Generated by scripts/art-raw-pixel.ts; method in src/lib/art/raw-pixel/metrics.ts. Do not edit by hand.",
  record: RAW_RECORD,
  layer: RAW_LAYER,
  time: layer.times[0],
  sample_rate: RAW_RATE,
  seconds: RAW_SECONDS,
  naive: stored(measure(renderNaive(frame), RAW_RATE)),
  bloop: stored(measure(renderBloop(frame), RAW_RATE)),
};
writeFileSync(join(process.cwd(), "public", "data", "art", "raw_pixel.json"), `${JSON.stringify(out, null, 1)}\n`, "utf8");
console.log(out);
