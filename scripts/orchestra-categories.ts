// Earth Orchestra's category table (src/lib/audio/orchestra/categories.json), generated from the record registry: the
// Official and Related indexes, each record's manifest (title, layer labels, play voices), and the app's own voices
// (Listen, Then vs Now) from public/mapping.json. Rules: src/lib/audio/orchestra/classify.ts. Unclassified records are
// listed, never guessed. Re-run after records are added: bun scripts/orchestra-categories.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { classifyRecord, CATEGORY_RULES, withMethods, type Classified, type RecordWords } from "../src/lib/audio/orchestra/classify";
import { APP_RECORD_IDS as DATA_RECORD_IDS, APP_RECORDS as DATA_RECORDS, METHOD_APPLIED_TO } from "../src/lib/earth/records";
import { en } from "../src/lib/i18n";

const DATA = join(process.cwd(), "public", "data");
const OUT = join(process.cwd(), "src", "lib", "audio", "orchestra", "categories.json");

interface IndexRow {
  record: string;
  title: string;
}
interface Manifest {
  title?: string;
  layers: { label?: string }[];
  play: { channels: { voice: string }[] }[];
}
interface MappingVoice {
  id: string;
  group: string;
  label: { en: string };
  source?: { dataset?: string };
}

const json = <T,>(path: string): T => JSON.parse(readFileSync(path, "utf8")) as T;

/** The Listen and Then vs Now voices: each is a record of its own (ChordRequest uses these ids). */
const APP_RECORDS = ["ocean", "rain", "snow", "heat", "monsoon", "water"] as const;

function appRecords(): RecordWords[] {
  const voices = json<{ voices: MappingVoice[] }>(join(process.cwd(), "public", "mapping.json")).voices;
  return APP_RECORDS.map((id) => {
    const v = voices.find((x) => x.id === id);
    if (!v) throw new Error(`mapping.json has no voice "${id}"`);
    return { id, title: `${v.label.en} ${v.source?.dataset ?? ""}`.trim(), layers: [] };
  });
}

function registry(folder: "official" | "related"): { words: RecordWords; voices: string[] }[] {
  const index = json<{ records: IndexRow[] }>(join(DATA, folder, "index.json")).records;
  return index.map((row) => {
    const m = json<Manifest>(join(DATA, folder, row.record, "manifest.json"));
    return {
      words: { id: row.record, title: `${row.title} ${m.title ?? ""}`, layers: m.layers.map((l) => l.label ?? "") },
      voices: [...new Set(m.play.flatMap((p) => p.channels.map((c) => c.voice)))],
    };
  });
}

/** DATA's records built from the shipped products (src/lib/earth/records.ts): classified from their own titles. */
const dataRecords = (): RecordWords[] => DATA_RECORD_IDS.map((id) => ({ id, title: en[DATA_RECORDS[id].titleKey], layers: [] }));

const records = [...registry("official"), ...registry("related")];
const classified: Classified[] = withMethods(
  [...appRecords().map(classifyRecord), ...dataRecords().map(classifyRecord), ...records.map((r) => classifyRecord(r.words))],
  METHOD_APPLIED_TO,
);

// A voice takes its record's category; a voice shared by records in different systems has none of its own (the
// record being played decides).
const voiceCategories = new Map<string, Set<string | null>>();
for (const r of records) {
  const c = classified.find((x) => x.id === r.words.id)?.category ?? null;
  for (const v of r.voices) voiceCategories.set(v, (voiceCategories.get(v) ?? new Set()).add(c));
}
for (const id of APP_RECORDS) voiceCategories.set(id, new Set([classified.find((x) => x.id === id)?.category ?? null]));

const table = {
  note: "Generated by scripts/orchestra-categories.ts from the record registry; rules in src/lib/audio/orchestra/classify.ts. Do not edit by hand.",
  rules: CATEGORY_RULES.map((r) => ({ category: r.category, pattern: r.pattern.source, why: r.why })),
  records: Object.fromEntries(classified.filter((c) => c.category !== null).map((c) => [c.id, c.category])),
  matched: Object.fromEntries(classified.flatMap((c) => (c.category === null ? [] : [[c.id, `${c.from}: ${c.matched}`]]))),
  voices: Object.fromEntries([...voiceCategories].map(([v, set]) => [v, set.size === 1 ? [...set][0] : null])),
  unclassified: classified.flatMap((c) => (c.category === null ? [{ id: c.id, reason: c.reason }] : [])),
};

writeFileSync(OUT, `${JSON.stringify(table, null, 1)}\n`, "utf8");
console.log(`${Object.keys(table.records).length} records classified, ${table.unclassified.length} unclassified:`);
for (const u of table.unclassified) console.log(`  ${u.id}: ${u.reason}`);
