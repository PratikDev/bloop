// The per-voice output trims (src/lib/audio/mix-trims.json), computed from the untrimmed measurements
// (docs/audio/mix_baseline.json, CV's mix pass) toward the loudness target in docs/audio/MIX.md, never typed: each mode's
// voices get trim = min(target − measured loudness, (master compressor threshold − headroom) − measured true peak), so a
// trim never pushes a mode's peaks into the master compressor. Applied at each voice channel's input (src/lib/audio/
// graph.ts): a constant gain after the voice, so value → pitch, value → density and every relative level stay as they
// are (public/mapping.json is not touched). Re-run after a new baseline: bun scripts/mix-trims.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const baseline = JSON.parse(readFileSync(join(ROOT, "docs", "audio", "mix_baseline.json"), "utf8")) as {
  target_lufs: number;
  modes: Record<string, { lufs: number; true_peak_dbtp: number }>;
};
const mapping = JSON.parse(readFileSync(join(ROOT, "public", "mapping.json"), "utf8")) as { global: { compressor: { thresholdDb: number } } };

/** Peaks stay this far under the master compressor's threshold (dB), so the trims never make it act. */
const HEADROOM_DB = 1;
/** Which channels each measured mode plays (the L2 engine's voices; the Turntable and the duet run on the jukebox engine
 *  and were already within tolerance of the target). */
const MODE_VOICES: Record<string, readonly string[]> = {
  "listen-ocean": ["ocean"],
  "listen-rain": ["rain", "snow"],
  "then-vs-now": ["heat", "monsoon", "water"],
};

const round = (x: number) => Math.round(x * 10) / 10;
const peakLimit = mapping.global.compressor.thresholdDb - HEADROOM_DB;
const voices: Record<string, { trim_db: number; from_mode: string; to_target_db: number; peak_room_db: number }> = {};
for (const [mode, ids] of Object.entries(MODE_VOICES)) {
  const m = baseline.modes[mode];
  if (!m) throw new Error(`mix_baseline.json has no mode "${mode}"`);
  const toTarget = baseline.target_lufs - m.lufs;
  const room = peakLimit - m.true_peak_dbtp;
  for (const id of ids) voices[id] = { trim_db: round(Math.min(toTarget, room)), from_mode: mode, to_target_db: round(toTarget), peak_room_db: round(room) };
}

const out = {
  note: "Generated by scripts/mix-trims.ts from docs/audio/mix_baseline.json and public/mapping.json's compressor. Do not edit by hand.",
  target_lufs: baseline.target_lufs,
  peak_limit_dbtp: peakLimit,
  voices,
};
writeFileSync(join(ROOT, "src", "lib", "audio", "mix-trims.json"), `${JSON.stringify(out, null, 1)}\n`, "utf8");
for (const [id, v] of Object.entries(voices)) console.log(`${id}: ${v.trim_db} dB (${v.from_mode}: ${v.to_target_db} to target, ${v.peak_room_db} peak room)`);
